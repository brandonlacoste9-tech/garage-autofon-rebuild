let lang = localStorage.getItem("ga-lang") || "en";

function applyLang(l) {
  lang = l;
  localStorage.setItem("ga-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "en" ? "FR" : "EN";
  document.title = l === "en"
    ? "Garage Autofon — Auto Repair in Pierrefonds | 30+ Years Family Owned"
    : "Garage Autofon — Réparation auto à Pierrefonds | Familial depuis 30+ ans";
}

document.getElementById("langToggle").addEventListener("click", () => {
  applyLang(lang === "en" ? "fr" : "en");
});

const menuBtn = document.getElementById("menuBtn");
